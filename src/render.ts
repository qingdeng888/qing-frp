import { FRPC_CONFIG_PATH, FRPS_BIN_PATH, FRPS_CONFIG_PATH, FRPS_SERVICE_NAME } from './config.js';
import { rangesToToml, serverReservedPorts } from './ports.js';
import { TomlWriter, tarr, tstr } from './toml.js';
import type { FrpsSettings, Node, PortRange, Proxy } from './types.js';
import { PORT_CONSUMING_TYPES } from './types.js';

/** Renders frps.toml / frpc.toml, systemd units and the one-click installer. */

export function renderFrpsToml(settings: FrpsSettings): string {
  const w = new TomlWriter();
  w.comment('Generated by frp-console. Manual edits will be overwritten.');
  w.comment(`Last update: ${new Date().toISOString()}`);
  w.blank();
  w.kv('bindAddr', settings.bindAddr || '0.0.0.0');
  w.kv('bindPort', settings.bindPort);
  w.kv('kcpBindPort', settings.kcpBindPort);
  w.kv('quicBindPort', settings.quicBindPort);
  w.kv('proxyBindAddr', settings.proxyBindAddr);
  w.kv('vhostHTTPPort', settings.vhostHttpPort);
  w.kv('vhostHTTPSPort', settings.vhostHttpsPort);
  w.kv('subDomainHost', settings.subdomainHost);
  w.blank();
  w.kv('auth.method', settings.authMethod || 'token');
  if ((settings.authMethod || 'token') === 'token') {
    w.kv('auth.token', settings.authToken);
  }
  w.blank();
  w.comment('Ports that frpc clients are allowed to bind remotely.');
  w.rawKv('allowPorts', rangesToToml(settings.allowPorts));
  w.kv('maxPortsPerClient', settings.maxPortsPerClient > 0 ? settings.maxPortsPerClient : undefined);
  w.blank();
  w.kv('transport.tls.force', settings.tlsForce || settings.tlsOnly ? true : undefined);
  w.kv('transport.tls.certFile', settings.tlsCertFile);
  w.kv('transport.tls.keyFile', settings.tlsKeyFile);
  w.kv('transport.tls.trustedCaFile', settings.tlsTrustedCaFile);
  // IMPORTANT: frp disables the application-layer heartbeat on BOTH sides when
  // tcpMux is enabled (the default), because tcpMux carries its own keepalive:
  //   frps: HeartbeatTimeout = -1 when tcpMux is on, else 90
  //   frpc: HeartbeatInterval = -1 when tcpMux is on, else 30
  // Writing an explicit heartbeatTimeout while tcpMux is enabled makes frps wait
  // for heartbeats that frpc never sends. frps then closes the control
  // connection every N seconds, and because tcpMux multiplexes every user
  // connection over that same connection, ALL tunnels drop at once and frpc has
  // to reconnect. Symptom: long-lived sessions (e.g. SSH) die on a fixed
  // interval. So only emit it when tcpMux is off, mirroring frp's own logic.
  if (!settings.tcpMux) {
    w.kv('transport.heartbeatTimeout', settings.heartbeatTimeout);
  }
  w.kv('transport.maxPoolCount', settings.maxPoolCount);
  w.kv('transport.tcpMux', settings.tcpMux);
  w.kv('transport.tcpMuxKeepaliveInterval', settings.tcpMuxKeepalive);
  w.blank();
  w.kv('udpPacketSize', settings.udpPacketSize);
  w.kv('natholeAnalysisDataReserveHours', settings.natholeReserveHours);
  w.kv('detailedErrorsToClient', settings.detailedErrors);
  w.kv('enablePrometheus', settings.enablePrometheus ? true : undefined);
  w.blank();

  if (settings.dashboardEnabled) {
    w.comment('frps built-in dashboard (optional, independent from this panel).');
    w.kv('webServer.addr', '0.0.0.0');
    w.kv('webServer.port', settings.dashboardPort);
    w.kv('webServer.user', settings.dashboardUser);
    w.kv('webServer.password', settings.dashboardPassword);
    w.blank();
  }

  w.comment('Logging: console so logs land in journald (journalctl -u frps -f).');
  w.rawKv('log.to', tstr('console'));
  w.kv('log.level', settings.logLevel || 'info');
  w.kv('log.maxDays', settings.logMaxDays);

  const extra = (settings.extraToml || '').trim();
  if (extra) {
    w.blank();
    w.comment('--- Extra TOML appended by operator ---');
    w.raw(extra);
  }

  return w.toString();
}

/**
 * systemd unit for frps.
 *
 * `binaryPath` should be the binary that will actually exist at start time.
 * Passing the versioned download path avoids copying onto a possibly-running
 * binary (which fails with ETXTBSY).
 */
export function renderFrpsUnit(binaryPath: string = FRPS_BIN_PATH): string {
  return `[Unit]
Description=frp server (managed by frp-console)
Documentation=https://github.com/fatedier/frp
After=network.target

[Service]
Type=simple
User=root
Restart=always
RestartSec=5s
ExecStart=${binaryPath} -c ${FRPS_CONFIG_PATH}
LimitNOFILE=1048576

[Install]
WantedBy=multi-user.target
`;
}

/** Remote port resolution result used when rendering a proxy block. */
export interface ResolvedPort {
  remotePort: number | null;
  random: boolean;
}

/**
 * Render one `[[proxies]]` block. Shared by the full frpc.toml and by the
 * panel's live preview so what the operator sees always matches the output.
 */
export function renderProxyBlock(
  proxy: Proxy,
  resolved: ResolvedPort | undefined,
  w: TomlWriter,
  opts: { includeHeaderComment?: boolean } = {},
): void {
  const rp = resolved ?? { remotePort: proxy.remotePort, random: proxy.remotePortRandom };

  w.table('[[proxies]]');
  w.kv('name', proxy.name);
  w.kv('type', proxy.type);
  if (proxy.type === 'tcpmux' && proxy.multiplexer) {
    w.kv('multiplexer', proxy.multiplexer);
  }
  if (proxy.type !== 'stcp' && proxy.type !== 'xtcp' && proxy.type !== 'sudp') {
    w.kv('localIP', proxy.localIp || '127.0.0.1');
    w.kv('localPort', proxy.localPort);
  }
  w.kv('secretKey', proxy.secretKey || undefined);

  if (PORT_CONSUMING_TYPES.includes(proxy.type)) {
    const port = rp.remotePort ?? proxy.remotePort;
    if (port && port > 0) {
      if (rp.random) {
        w.comment('remotePort auto-allocated by frp-console from the frps allowPorts pool');
      }
      w.kv('remotePort', port);
    } else {
      // Pool exhausted (or explicitly dynamic): let frps choose at runtime,
      // which also draws from the server-side allowPorts ranges.
      w.comment('remotePort = 0 -> frps assigns a random port from its allowPorts ranges');
      w.kv('remotePort', 0);
    }
  }

  if (proxy.type === 'http' || proxy.type === 'https' || proxy.type === 'tcpmux') {
    if (proxy.customDomains.length) w.rawKv('customDomains', tarr(proxy.customDomains));
    w.kv('subdomain', proxy.subdomain || undefined);
    if (proxy.locations.length && (proxy.type === 'http' || proxy.type === 'https')) {
      w.rawKv('locations', tarr(proxy.locations));
    }
    w.kv('httpUser', proxy.httpUser || undefined);
    w.kv('httpPassword', proxy.httpPassword || undefined);
    w.kv('hostHeaderRewrite', proxy.hostHeaderRewrite || undefined);
  }

  w.kv('transport.useEncryption', proxy.useEncryption ? true : undefined);
  w.kv('transport.useCompression', proxy.useCompression ? true : undefined);
  w.kv('transport.bandwidthLimit', proxy.bandwidthLimit || undefined);
  w.kv('transport.proxyProtocolVersion', proxy.proxyProtocol || undefined);
}

/** Render a standalone block for the panel's live preview. */
export function renderProxyBlockText(
  proxy: Proxy,
  resolved?: ResolvedPort,
): string {
  const w = new TomlWriter();
  renderProxyBlock(proxy, resolved, w);
  return w.toString();
}

export function renderFrpcToml(
  node: Node,
  proxies: Proxy[],
  opts: {
    serverAddr: string;
    serverPort: number;
    authToken: string;
    resolved: Map<number, ResolvedPort>;
    /**
     * Must match the frps side. frp multiplexes user connections over the
     * control connection when enabled, so a mismatch between frps and frpc
     * changes how connections are carried and can break long-lived sessions.
     */
    tcpMux?: boolean;
  },
): string {
  const w = new TomlWriter();
  w.comment('Generated by frp-console. Manual edits will be overwritten.');
  w.comment(`Node: ${node.name} (#${node.id})`);
  w.comment(`Last update: ${new Date().toISOString()}`);
  w.blank();
  w.kv('serverAddr', opts.serverAddr);
  w.kv('serverPort', opts.serverPort);
  w.kv('user', node.user || undefined);
  w.blank();
  w.kv('auth.method', 'token');
  w.kv('auth.token', opts.authToken);
  w.blank();
  // The comment differs per platform: journald is Linux-only.
  w.comment('Logging: console, so the service manager captures the output.');
  w.rawKv('log.to', tstr('console'));
  w.kv('log.level', node.logLevel || 'info');
  w.kv('loginFailExit', node.loginFailExit);

  // Keep tcpMux in lockstep with frps (see the note in renderFrpsToml).
  if (opts.tcpMux !== undefined) {
    w.blank();
    w.comment('Must match frps transport.tcpMux.');
    w.kv('transport.tcpMux', opts.tcpMux);
  }

  const protocol = node.protocol || 'tcp';
  if (protocol !== 'tcp') {
    w.blank();
    w.comment(`Transport protocol: ${protocol}`);
    w.kv('transport.protocol', protocol);
    w.kv('transport.tls.enable', true);
  } else if (node.tlsEnable) {
    w.blank();
    w.kv('transport.tls.enable', true);
  }

  const enabled = proxies.filter((p) => p.enabled);
  for (const proxy of enabled) {
    renderProxyBlock(proxy, opts.resolved.get(proxy.id), w);
  }

  const extra = (node.extraToml || '').trim();
  if (extra) {
    w.blank();
    w.comment('--- Extra TOML appended by operator ---');
    w.raw(extra);
  }

  return w.toString();
}

export function renderFrpcUnit(node: Node): string {
  const dir = node.installDir || '/etc/frp';
  return `[Unit]
Description=frp client for ${node.name} (managed by frp-console)
Documentation=https://github.com/fatedier/frp
After=network.target
Wants=network-online.target

[Service]
Type=simple
Restart=always
RestartSec=5s
ExecStart=${dir}/frpc -c ${dir}/frpc.toml
LimitNOFILE=1048576

[Install]
WantedBy=multi-user.target
`;
}

/** frps-side ports that must never be handed out to a client. */
export function reservedPortsFor(settings: FrpsSettings): Set<number> {
  return serverReservedPorts(settings);
}

export function defaultAllowPorts(): PortRange[] {
  // Kept inside the range commonly opened by NAT/firewall for this deployment
  // (37000-37099), leaving 37000-37002 for the panel, frps and dashboard.
  return [{ start: 37010, end: 37099 }];
}
